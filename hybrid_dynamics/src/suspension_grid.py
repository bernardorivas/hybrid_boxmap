@dataclass(frozen=True)
class GeneratorKey:
    """A generator ``K_j(nu)`` (``kind='K'``) or ``Q_j(nu, k)`` (``'Q'``).

    ``cell`` is the ambient level-``level`` address ``(i, k)`` of ``nu``.
    """

    kind: str
    level: int
    cell: tuple[int, int]
    phase: int = -1


@dataclass(frozen=True)
class LocatedPoints:
    """Closed-cell location of points: ``(point index, piece id)`` incidences."""

    point_index: IntArray
    piece: IntArray

    def pieces_of(self, index: int) -> IntArray:
        return self.piece[self.point_index == index]


@dataclass
class SuspensionGrid:
    """The suspension grid ``Xi_n`` on the window ``D = Sigma(R)``.

    Piece ids ``0 .. n_base-1`` are the finest base cells; piece
    ``n_base + J * n_phase + k`` is the handle piece ``pi(J x I_{n,k})``.
    Atoms (the elements of ``Xi_n``) are indexed ``0 .. n_atoms-1``.
    """

    window: DyadicBaseWindow
    guard: GuardResetSpec
    level: int
    cells_per_axis: int
    cell_widths: FloatArray
    base_cell_index: IntArray  # (m, m) -> base piece id or -1
    base_addresses: IntArray  # (n_base, 2) ambient addresses (ix, iy)
    u_edges: FloatArray  # guard partition breakpoints, length n_guard + 1
    n_phase: int
    guard_bottom_cells: tuple[IntArray, ...]  # finest cells containing gamma(J)
    guard_top_cells: tuple[IntArray, ...]  # finest cells containing r(gamma(J))
    n_generators: int  # generators K_j(mu), Q_j(mu, k) with a piece, j <= n
    atom_of_piece: IntArray
    atom_offsets: IntArray  # CSR offsets into atom_pieces
    atom_pieces: IntArray
    d_map: IntArray  # d_n: base piece (= finest base cell) -> atom
    piece_adjacency: sparse.csr_matrix
    atom_adjacency: sparse.csr_matrix
    guard_profile: _CurveProfile
    reset_profile: _CurveProfile
    location_tolerance: float
    metadata: dict[str, Any] = field(default_factory=dict)
    _reference: tuple[Any, ...] | None = field(default=None, repr=False, compare=False)

    # -- generators -------------------------------------------------------------
    @property
    def signatures(self) -> tuple[tuple[int, ...], ...]:
        """Sorted generator ids of every piece (computed on first use)."""

        return self._reference_signatures()[0]

    @property
    def generators(self) -> tuple[GeneratorKey, ...]:
        """Generator keys in the order of their ids (computed on first use)."""

        return self._reference_signatures()[1]

    def _reference_signatures(self) -> tuple[Any, ...]:
        if self._reference is None:
            self._reference = reference_signatures(self)
        return self._reference

    # -- sizes ------------------------------------------------------------
    @property
    def a_n(self) -> float:
        return 1.0 / self.n_phase

    @property
    def n_base(self) -> int:
        return int(self.base_addresses.shape[0])

    @property
    def n_guard(self) -> int:
        return int(self.u_edges.shape[0] - 1)

    @property
    def n_handle(self) -> int:
        return self.n_guard * self.n_phase

    @property
    def n_pieces(self) -> int:
        return self.n_base + self.n_handle

    @property
    def n_atoms(self) -> int:
        return int(self.atom_offsets.shape[0] - 1)

    def atom(self, index: int) -> IntArray:
        return self.atom_pieces[self.atom_offsets[index] : self.atom_offsets[index + 1]]

    # -- piece geometry ----------------------------------------------------
    def piece_kind(self, piece: npt.ArrayLike) -> IntArray:
        values = np.asarray(piece, dtype=np.int64)
        return np.where(values < self.n_base, BASE_PIECE, HANDLE_PIECE)

    def handle_piece(self, guard_index: npt.ArrayLike, phase: npt.ArrayLike) -> IntArray:
        return (
            self.n_base
            + np.asarray(guard_index, dtype=np.int64) * self.n_phase
            + np.asarray(phase, dtype=np.int64)
        )

    def handle_indices(self, piece: npt.ArrayLike) -> tuple[IntArray, IntArray]:
        values = np.asarray(piece, dtype=np.int64) - self.n_base
        return values // self.n_phase, values % self.n_phase

    def base_bounds(self, piece: npt.ArrayLike) -> FloatArray:
        """``(N, 4)`` rectangles ``(x0, y0, x1, y1)`` of base pieces."""

        addresses = self.base_addresses[np.asarray(piece, dtype=np.int64)]
        lower = self._ambient_lower + addresses * self.cell_widths
        return np.concatenate((lower, lower + self.cell_widths), axis=-1)

    def handle_bounds(self, piece: npt.ArrayLike) -> FloatArray:
        """``(N, 4)`` rectangles ``(u0, s0, u1, s1)`` of handle pieces."""

        guard_index, phase = self.handle_indices(piece)
        return np.stack(
            (
                self.u_edges[guard_index],
                phase / self.n_phase,
                self.u_edges[guard_index + 1],
                (phase + 1) / self.n_phase,
            ),
            axis=-1,
        )

    @property
    def _ambient_lower(self) -> FloatArray:
        return np.array(
            [self.window.ambient_bounds[0][0], self.window.ambient_bounds[1][0]]
        )

    # -- d_n and the base readout -----------------------------------------
    def d(self, base_cells: npt.ArrayLike) -> IntArray:
        """The injection ``d_n : X_n -> Xi_n`` of ``prop:suspension-grid``."""

        return self.d_map[np.asarray(base_cells, dtype=np.int64)]

    def base_readout(self, atoms: npt.ArrayLike) -> IntArray:
        """``d_n^{-1}(U)``: base cells ``mu`` with ``d_n(mu) in U``.

        By ``prop:finite-grid-preimage`` its union is the regularized preimage
        ``rho_n(|U|)``.
        """

        selected = np.zeros(self.n_atoms, dtype=bool)
        selected[np.asarray(atoms, dtype=np.int64)] = True
        return np.flatnonzero(selected[self.d_map])

    # -- point location -----------------------------------------------------
    def _axis_candidates(self, values: FloatArray, axis: int) -> tuple[IntArray, IntArray]:
        """Closed cell indices along one axis: ``(point index, cell index)``."""

        lower = self.window.ambient_bounds[axis][0]
        width = self.cell_widths[axis]
        fractional = (values - lower) / width
        nearest = np.rint(fractional)
        on_line = np.abs(fractional - nearest) <= self.location_tolerance
        floor = np.floor(fractional).astype(np.int64)
        rows = [np.arange(values.shape[0])]
        cells = [np.where(on_line, nearest.astype(np.int64), floor)]
        rows.append(np.flatnonzero(on_line))
        cells.append(nearest[on_line].astype(np.int64) - 1)
        row = np.concatenate(rows)
        cell = np.concatenate(cells)
        keep = (cell >= 0) & (cell < self.cells_per_axis) & np.isfinite(values[row])
        return row[keep], cell[keep]

    def locate_base_cells(self, points: npt.ArrayLike) -> LocatedPoints:
        """Finest base cells whose closed rectangle contains each point."""

        values = np.atleast_2d(np.asarray(points, dtype=np.float64))
        rows_x, cells_x = self._axis_candidates(values[:, 0], 0)
        rows_y, cells_y = self._axis_candidates(values[:, 1], 1)
        if rows_x.size == 0 or rows_y.size == 0:
            return LocatedPoints(np.zeros(0, np.int64), np.zeros(0, np.int64))
        # Join the per-axis candidates on the point index (at most 2 x 2).
        order_x = np.argsort(rows_x, kind="stable")
        rows_x, cells_x = rows_x[order_x], cells_x[order_x]
        order_y = np.argsort(rows_y, kind="stable")
        rows_y, cells_y = rows_y[order_y], cells_y[order_y]
        point_list: list[IntArray] = []
        piece_list: list[IntArray] = []
        for shift_x in range(2):
            for shift_y in range(2):
                # k-th candidate of each axis for the same point.
                sel_x = _kth_per_group(rows_x, shift_x)
                sel_y = _kth_per_group(rows_y, shift_y)
                common, ix, iy = np.intersect1d(
                    rows_x[sel_x], rows_y[sel_y], return_indices=True
                )
                if common.size == 0:
                    continue
                pieces = self.base_cell_index[
                    cells_x[sel_x][ix], cells_y[sel_y][iy]
                ]
                keep = pieces >= 0
                point_list.append(common[keep])
                piece_list.append(pieces[keep])
        if not point_list:
            return LocatedPoints(np.zeros(0, np.int64), np.zeros(0, np.int64))
        return LocatedPoints(np.concatenate(point_list), np.concatenate(piece_list))

    def locate_guard_intervals(self, u: npt.ArrayLike) -> tuple[IntArray, IntArray]:
        """Closed guard intervals ``J`` containing each coordinate."""

        values = np.atleast_1d(np.asarray(u, dtype=np.float64))
        scale = self.guard_scale
        tolerance = self.location_tolerance * scale
        inside = (values >= self.u_edges[0] - tolerance) & (
            values <= self.u_edges[-1] + tolerance
        )
        clipped = np.clip(values, self.u_edges[0], self.u_edges[-1])
        index = np.searchsorted(self.u_edges, clipped, side="right") - 1
        index = np.clip(index, 0, self.n_guard - 1)
        rows = [np.flatnonzero(inside)]
        cells = [index[inside]]
        near_lower = inside & (np.abs(clipped - self.u_edges[index]) <= tolerance) & (index > 0)
        rows.append(np.flatnonzero(near_lower))
        cells.append(index[near_lower] - 1)
        near_upper = (
            inside
            & (np.abs(clipped - self.u_edges[index + 1]) <= tolerance)
            & (index + 1 < self.n_guard)
        )
        rows.append(np.flatnonzero(near_upper))
        cells.append(index[near_upper] + 1)
        return np.concatenate(rows), np.concatenate(cells)

    def locate_phases(self, s: npt.ArrayLike) -> tuple[IntArray, IntArray]:
        """Closed phase intervals ``I_{n,k}`` containing each phase in ``[0,1]``."""

        values = np.atleast_1d(np.asarray(s, dtype=np.float64))
        scaled = values * self.n_phase
        nearest = np.rint(scaled)
        on_line = np.abs(scaled - nearest) <= self.location_tolerance
        index = np.where(on_line, nearest, np.floor(scaled)).astype(np.int64)
        rows = [np.arange(values.shape[0])]
        cells = [index]
        rows.append(np.flatnonzero(on_line))
        cells.append(index[on_line] - 1)
        row = np.concatenate(rows)
        cell = np.concatenate(cells)
        keep = (cell >= 0) & (cell < self.n_phase)
        return row[keep], cell[keep]

    @property
    def guard_scale(self) -> float:
        return float(max(abs(self.u_edges[-1] - self.u_edges[0]), 1.0e-300))

    def guard_membership(self, points: npt.ArrayLike) -> FloatArray:
        """Guard coordinate of base points on ``G cap R``; ``nan`` otherwise."""

        values = np.atleast_2d(np.asarray(points, dtype=np.float64))
        u = self.guard.coordinate(values)
        inside = np.isfinite(u)
        tolerance = self.location_tolerance * self.guard_scale
        inside &= (u >= self.u_edges[0] - tolerance) & (u <= self.u_edges[-1] + tolerance)
        result = np.full(values.shape[0], np.nan)
        if np.any(inside):
            clipped = np.clip(u[inside], self.u_edges[0], self.u_edges[-1])
            residual = np.max(
                np.abs(self.guard.gamma(clipped) - values[inside]) / self.cell_widths,
                axis=1,
            )
            ok = residual <= self.location_tolerance
            indices = np.flatnonzero(inside)[ok]
            result[indices] = clipped[ok]
        return result

    def reset_membership(self, points: npt.ArrayLike) -> FloatArray:
        """``u`` with ``r(gamma(u)) = x`` for base points on ``r(G cap R)``."""

        values = np.atleast_2d(np.asarray(points, dtype=np.float64))
        u = _invert_curve(
            self.guard.reset, self.reset_profile, self.guard.u_bounds, values
        )
        residual = np.max(np.abs(self.guard.reset(u) - values) / self.cell_widths, axis=1)
        return np.where(residual <= self.location_tolerance, u, np.nan)

    def locate_base_points(self, points: npt.ArrayLike) -> LocatedPoints:
        """Pieces of ``Xi_n`` whose closure contains ``iota(x)``.

        A point on ``G cap R`` also lies in the handle pieces at phase zero
        over it, and a point of ``r(G cap R)`` in the handle pieces at phase
        one over its reset preimage (the identifications ``pi(g,0)=iota(g)``
        and ``pi(g,1)=iota(r(g))``).  Points outside ``R`` are not located.
        """

        values = np.atleast_2d(np.asarray(points, dtype=np.float64))
        located = self.locate_base_cells(values)
        rows = [located.point_index]
        pieces = [located.piece]
        u_guard = self.guard_membership(values)
        on_guard = np.flatnonzero(np.isfinite(u_guard))
        if on_guard.size:
            guard_rows, guard_cells = self.locate_guard_intervals(u_guard[on_guard])
            rows.append(on_guard[guard_rows])
            pieces.append(self.handle_piece(guard_cells, 0))
        u_reset = self.reset_membership(values)
        on_reset = np.flatnonzero(np.isfinite(u_reset))
        if on_reset.size:
            reset_rows, reset_cells = self.locate_guard_intervals(u_reset[on_reset])
            rows.append(on_reset[reset_rows])
            pieces.append(self.handle_piece(reset_cells, self.n_phase - 1))
        return _unique_located(np.concatenate(rows), np.concatenate(pieces))

    def locate_handle_points(self, u: npt.ArrayLike, s: npt.ArrayLike) -> LocatedPoints:
        """Pieces whose closure contains ``pi(gamma(u), s)``.

        Coordinates outside ``G cap R`` are not located.  At ``s = 0`` and
        ``s = 1`` the base cells containing ``gamma(u)`` and ``r(gamma(u))``
        are added (the two sides of an identification).
        """

        u_values = np.atleast_1d(np.asarray(u, dtype=np.float64))
        s_values = np.atleast_1d(np.asarray(s, dtype=np.float64))
        guard_rows, guard_cells = self.locate_guard_intervals(u_values)
        phase_rows, phase_cells = self.locate_phases(s_values)
        rows: list[IntArray] = []
        pieces: list[IntArray] = []
        for first in range(3):
            sel_g = _kth_per_group_unsorted(guard_rows, first)
            for second in range(2):
                sel_p = _kth_per_group_unsorted(phase_rows, second)
                common, ig, ip = np.intersect1d(
                    guard_rows[sel_g], phase_rows[sel_p], return_indices=True
                )
                if common.size:
                    rows.append(common)
                    pieces.append(
                        self.handle_piece(guard_cells[sel_g][ig], phase_cells[sel_p][ip])
                    )
        tolerance = self.location_tolerance
        in_window = np.zeros(u_values.shape[0], dtype=bool)
        in_window[guard_rows] = True
        at_zero = np.flatnonzero(in_window & (s_values <= tolerance))
        if at_zero.size:
            located = self.locate_base_cells(
                self.guard.gamma(np.clip(u_values[at_zero], *self.guard.u_bounds))
            )
            rows.append(at_zero[located.point_index])
            pieces.append(located.piece)
        at_one = np.flatnonzero(in_window & (s_values >= 1.0 - tolerance))
        if at_one.size:
            located = self.locate_base_cells(
                self.guard.reset(np.clip(u_values[at_one], *self.guard.u_bounds))
            )
            rows.append(at_one[located.point_index])
            pieces.append(located.piece)
        if not rows:
            return LocatedPoints(np.zeros(0, np.int64), np.zeros(0, np.int64))
        return _unique_located(np.concatenate(rows), np.concatenate(pieces))

    def base_points_in_window(self, points: npt.ArrayLike) -> npt.NDArray[np.bool_]:
        values = np.atleast_2d(np.asarray(points, dtype=np.float64))
        located = self.locate_base_cells(values)
        result = np.zeros(values.shape[0], dtype=bool)
        result[located.point_index] = True
        return result

    # -- refinement ---------------------------------------------------------
    def piece_parent(self, coarse: "SuspensionGrid") -> IntArray:
        """The piece of ``coarse`` containing each piece of ``self``."""

        if coarse.level > self.level or coarse.window != self.window:
            raise ValueError("coarse grid must be a lower level of the same window")
        shift = self.level - coarse.level
        parents = np.empty(self.n_pieces, dtype=np.int64)
        base_parent = coarse.base_cell_index[
            self.base_addresses[:, 0] >> shift, self.base_addresses[:, 1] >> shift
        ]
        if np.any(base_parent < 0):
            raise AssertionError("a finer base cell has no coarser parent in R")
        parents[: self.n_base] = base_parent
        guard_index, phase = self.handle_indices(np.arange(self.n_base, self.n_pieces))
        middle = 0.5 * (self.u_edges[guard_index] + self.u_edges[guard_index + 1])
        coarse_guard = np.searchsorted(coarse.u_edges, middle, side="right") - 1
        parents[self.n_base :] = coarse.handle_piece(coarse_guard, phase >> shift)
        return parents

    def refinement_map(self, coarse: "SuspensionGrid") -> IntArray:
        """``q_{mn}``: the atom of ``coarse`` containing each atom of ``self``.

        Raises if some atom of ``self`` is not contained in a single atom of
        ``coarse`` (that is, if ``Xi_m`` fails to refine ``Xi_n``).
        """

        parent_atoms = coarse.atom_of_piece[self.piece_parent(coarse)]
        result = np.full(self.n_atoms, -1, dtype=np.int64)
        for atom in range(self.n_atoms):
            values = np.unique(parent_atoms[self.atom(atom)])
            if values.size != 1:
                raise AssertionError(
                    f"atom {atom} of level {self.level} meets {values.size} atoms of "
                    f"level {coarse.level}"
                )
            result[atom] = values[0]
        return result

    def summary(self) -> dict[str, Any]:
        d_atoms = np.zeros(self.n_atoms, dtype=bool)
        d_atoms[self.d_map] = True
        sizes = np.diff(self.atom_offsets)
        return {
            "level": self.level,
            "a_n": self.a_n,
            "base_cells_per_axis": self.cells_per_axis,
            "base_cell_widths": [float(value) for value in self.cell_widths],
            "base_pieces": self.n_base,
            "guard_intervals": self.n_guard,
            "phase_intervals": self.n_phase,
            "handle_pieces": self.n_handle,
            "pieces": self.n_pieces,
            "generators": self.n_generators,
            "atoms": self.n_atoms,
            "atoms_in_d_image": int(np.count_nonzero(d_atoms)),
            "atoms_without_base_cell": int(self.n_atoms - np.count_nonzero(d_atoms)),
            "max_pieces_per_atom": int(sizes.max()) if sizes.size else 0,
            "guard_curve_straight": self.guard_profile.straight,
            "reset_curve_straight": self.reset_profile.straight,
        }


def _kth_per_group(sorted_rows: IntArray, k: int) -> IntArray:
    """Indices of the ``k``-th entry of each run in a sorted row array."""

    if sorted_rows.size == 0:
        return np.zeros(0, dtype=np.int64)
    starts = np.r_[0, np.flatnonzero(np.diff(sorted_rows)) + 1]
    counts = np.diff(np.r_[starts, sorted_rows.size])
    keep = counts > k
    return starts[keep] + k


def _kth_per_group_unsorted(rows: IntArray, k: int) -> IntArray:
    order = np.argsort(rows, kind="stable")
    return order[_kth_per_group(rows[order], k)]


def _unique_located(rows: IntArray, pieces: IntArray) -> LocatedPoints:
    if rows.size == 0:
        return LocatedPoints(rows.astype(np.int64), pieces.astype(np.int64))
    pairs = np.unique(np.stack((rows, pieces), axis=1), axis=0)
    return LocatedPoints(pairs[:, 0].astype(np.int64), pairs[:, 1].astype(np.int64))


