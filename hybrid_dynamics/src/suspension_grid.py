def build_suspension_grid(
    window: DyadicBaseWindow,
    guard: GuardResetSpec,
    level: int,
    *,
    location_tolerance: float = 1.0e-9,
) -> SuspensionGrid:
    """Construct ``Xi_n`` for ``n = level`` (the cofiltration of the paper).

    ``Xi_n`` is generated by ``K_j(mu)`` and ``Q_j(mu, k)`` for all
    ``0 <= j <= n``, ``mu in X_j`` and ``1 <= k <= 2^{j+2} - 2``, which is the
    manuscript's recursive definition ``Xi_n = Xi_{n-1} ^ Xi_n(X_n)``.
    """

    if isinstance(level, bool) or not isinstance(level, (int, np.integer)) or level < 0:
        raise ValueError("level must be a nonnegative integer")
    level = int(level)
    m = window.cells_per_axis(level)
    lower = np.array([window.ambient_bounds[0][0], window.ambient_bounds[1][0]])
    upper = np.array([window.ambient_bounds[0][1], window.ambient_bounds[1][1]])
    widths = (upper - lower) / m

    # Finest base cells of R.
    ix, iy = np.meshgrid(np.arange(m), np.arange(m), indexing="ij")
    addresses = np.stack((ix.ravel(), iy.ravel()), axis=1).astype(np.int64)
    centers = lower + (addresses + 0.5) * widths
    if window.region is None:
        mask = np.ones(addresses.shape[0], dtype=bool)
    else:
        mask = np.asarray(window.region(centers), dtype=bool).reshape(-1)
        if mask.shape[0] != addresses.shape[0]:
            raise ValueError("region must return one Boolean per cell center")
    addresses = addresses[mask]
    if addresses.shape[0] == 0:
        raise ValueError("the window contains no finest cell")
    base_cell_index = np.full((m, m), -1, dtype=np.int64)
    base_cell_index[addresses[:, 0], addresses[:, 1]] = np.arange(addresses.shape[0])
    n_base = int(addresses.shape[0])

    # Guard and reset curve data.
    scale = (float(upper[0] - lower[0]), float(upper[1] - lower[1]))
    guard_profile = _curve_profile(guard.gamma, guard.u_bounds, scale=scale, name="guard_point")
    reset_profile = _curve_profile(guard.reset, guard.u_bounds, scale=scale, name="reset_point")
    grid_lines = [lower[axis] + np.arange(m + 1) * widths[axis] for axis in range(2)]
    breakpoints = np.concatenate(
        (
            np.asarray(guard.u_bounds, dtype=np.float64),
            _curve_grid_crossings(guard.gamma, guard_profile, guard.u_bounds, grid_lines),
            _curve_grid_crossings(guard.reset, reset_profile, guard.u_bounds, grid_lines),
        )
    )
    breakpoints = np.sort(breakpoints)
    span = guard.u_bounds[1] - guard.u_bounds[0]
    merge_tolerance = location_tolerance * span
    u_edges = [breakpoints[0]]
    for value in breakpoints[1:]:
        if value - u_edges[-1] > merge_tolerance:
            u_edges.append(value)
    u_edges_array = np.asarray(u_edges, dtype=np.float64)
    u_edges_array[0], u_edges_array[-1] = guard.u_bounds
    n_guard = int(u_edges_array.shape[0] - 1)

    grid = SuspensionGrid(
        window=window,
        guard=guard,
        level=level,
        cells_per_axis=m,
        cell_widths=widths,
        base_cell_index=base_cell_index,
        base_addresses=addresses,
        u_edges=u_edges_array,
        n_phase=2 ** (level + 2),
        guard_bottom_cells=(),
        guard_top_cells=(),
        n_generators=0,
        atom_of_piece=np.zeros(0, dtype=np.int64),
        atom_offsets=np.zeros(1, dtype=np.int64),
        atom_pieces=np.zeros(0, dtype=np.int64),
        d_map=np.zeros(0, dtype=np.int64),
        piece_adjacency=sparse.csr_matrix((0, 0)),
        atom_adjacency=sparse.csr_matrix((0, 0)),
        guard_profile=guard_profile,
        reset_profile=reset_profile,
        location_tolerance=float(location_tolerance),
    )

    # Finest cells meeting gamma(J) and r(gamma(J)) along the open interval J.
    middles = 0.5 * (u_edges_array[:-1] + u_edges_array[1:])

    def cells_at(points: FloatArray) -> list[IntArray]:
        located = grid.locate_base_cells(points)
        return [
            np.unique(located.piece[located.point_index == index])
            for index in range(points.shape[0])
        ]

    bottom_cells = cells_at(guard.gamma(middles))
    top_cells = cells_at(guard.reset(middles))
    for index in range(n_guard):
        if bottom_cells[index].size == 0:
            raise UnsupportedSuspensionGridError(
                "the guard parametrization leaves the window R at "
                f"u={middles[index]!r}; u_bounds must describe G cap R"
            )
        if top_cells[index].size == 0:
            raise UnsupportedSuspensionGridError(
                "r(G cap R) is not contained in R near "
                f"u={middles[index]!r}; the top collars would lie over cells "
                "outside the window, which this implementation does not support"
            )
    grid.guard_bottom_cells = tuple(bottom_cells)
    grid.guard_top_cells = tuple(top_cells)

    # Atoms: nonempty classes of pieces with a common signature, numbered in
    # the order of their first piece.
    atom_of_piece, n_generators = _signature_classes(
        addresses, grid.guard_bottom_cells, grid.guard_top_cells, level, grid.n_phase,
        window.level_offset,
    )
    order = np.argsort(atom_of_piece, kind="stable")
    counts = np.bincount(atom_of_piece)
    atom_offsets = np.r_[0, np.cumsum(counts)].astype(np.int64)

    grid.n_generators = int(n_generators)
    grid.atom_of_piece = atom_of_piece
    grid.atom_offsets = atom_offsets
    grid.atom_pieces = order.astype(np.int64)
    grid.d_map = atom_of_piece[:n_base].copy()

    # Closed-set incidence of pieces in the suspension quotient.
    grid.piece_adjacency = _piece_adjacency(grid)
    membership = sparse.csr_matrix(
        (np.ones(grid.n_pieces), (np.arange(grid.n_pieces), atom_of_piece)),
        shape=(grid.n_pieces, grid.n_atoms),
    )
    atom_adjacency = (membership.T @ grid.piece_adjacency @ membership).tocsr()
    atom_adjacency.data[:] = 1.0
    grid.atom_adjacency = atom_adjacency
    grid.metadata = {
        "construction": "paper suspension grid Xi_n (def:suspension-grid), levels 0..n",
        "window": window.name,
        "guard": guard.name,
    }
    return grid


def _last_top_levels(level: int, n_phase: int) -> IntArray:
    """For each phase ``k``: the largest ``j`` with ``k >> (n-j) = 2^{j+2}-1``, or ``-1``.

    The levels ``j`` at which the phase piece ``k`` lies in a top collar
    ``[1 - a_j, 1]`` form the initial segment ``0, ..., J(k)``.
    """

    phases = np.arange(n_phase, dtype=np.int64)
    result = np.full(n_phase, -1, dtype=np.int64)
    for j in range(level + 1):
        result[(phases >> (level - j)) == 2 ** (j + 2) - 1] = j
    return result


def _padded_rows(rows: Sequence[IntArray], width: int) -> IntArray:
    result = np.full((len(rows), width), -1, dtype=np.int64)
    for index, values in enumerate(rows):
        result[index, : values.size] = values
    return result


def _signature_classes(
    addresses: IntArray,
    bottom_cells: Sequence[IntArray],
    top_cells: Sequence[IntArray],
    level: int,
    n_phase: int,
    level_offset: int,
) -> tuple[IntArray, int]:
    """Atoms of the pieces (numbered by first piece) and the number of generators.

    The generator signature of a piece (the set of ``K_j(nu)`` and
    ``Q_j(nu, k)`` containing it) is determined by a short key:

    * a base piece ``mu`` lies in ``K_j(mu_j)`` for its ancestors ``mu_j``,
      and in no ``Q``: key ``K{mu}``;
    * a handle piece over ``J`` at phase ``0`` lies in ``K_j`` of the
      level-``j`` cells meeting ``gamma(J)`` for every ``j``: key ``K B_n(J)``
      with ``B_n(J)`` the finest cells meeting ``gamma(J)``;
    * at the last phase: key ``K T_n(J)`` with ``T_n(J)`` the finest cells
      meeting ``r(gamma(J))``;
    * at a middle phase ``k``: it lies in ``Q_n(nu, k)`` for ``nu`` in
      ``B_n(J)``, in ``K_j`` or ``Q_j`` of the ancestors of ``B_n(J)`` at the
      levels where ``k`` is a bottom or middle phase, and in ``K_j`` of the
      level-``j`` cells of ``T_n(J)`` at the levels ``j <= J(k)`` where it is
      a top phase (:func:`_last_top_levels`): key ``(k, B_n(J), J(k),
      T_{J(k)}(J))``.

    A ``K``-only signature is determined by its finest-level generators,
    which are ``K_n`` of the given cells, so two ``K``-only keys give the same
    signature exactly when their cell sets agree; a middle key contains
    ``Q_n(., k)`` and so never equals a ``K``-only one.  Base pieces are the
    first pieces and have distinct signatures, so the atom of base piece
    ``mu`` is ``mu``; a handle piece with key ``K{mu}`` joins that atom.  This
    reproduces the first-occurrence numbering of the signature classes, which
    :func:`reference_signatures` computes from the generator sets
    themselves (the tests compare the two).
    """

    n_base = int(addresses.shape[0])
    n_guard = len(bottom_cells)
    width = max(
        1,
        max((values.size for values in bottom_cells), default=0),
        max((values.size for values in top_cells), default=0),
    )
    bottom = _padded_rows([np.asarray(values, dtype=np.int64) for values in bottom_cells], width)
    top = _padded_rows([np.asarray(values, dtype=np.int64) for values in top_cells], width)
    # Level-j cells of T_n(J), encoded ix * 2^(j + offset) + iy, per level.
    top_by_level = np.full((level + 1, n_guard, width), -1, dtype=np.int64)
    for j in range(level + 1):
        side = 2 ** (j + level_offset)
        rows = []
        for values in top_cells:
            coarse = addresses[np.asarray(values, dtype=np.int64)] >> (level - j)
            rows.append(np.unique(coarse[:, 0] * side + coarse[:, 1]))
        top_by_level[j] = _padded_rows(rows, width)

    # Keys (class, phase, B or K set, J(k), T_J set) of the handle pieces.
    top_level = _last_top_levels(level, n_phase)
    columns = 3 + 2 * width
    keys = np.full((n_guard, n_phase, columns), -1, dtype=np.int64)
    keys[:, :, 0] = 1
    keys[:, :, 1] = np.arange(n_phase, dtype=np.int64)[None, :]
    keys[:, :, 2 : 2 + width] = bottom[:, None, :]
    keys[:, :, 2 + width] = top_level[None, :]
    has_top = np.flatnonzero(top_level >= 0)
    keys[:, has_top, 3 + width :] = top_by_level[top_level[has_top]].transpose(1, 0, 2)
    keys[:, 0, :] = -1
    keys[:, 0, 0] = 0
    keys[:, 0, 2 : 2 + width] = bottom
    keys[:, n_phase - 1, :] = -1
    keys[:, n_phase - 1, 0] = 0
    keys[:, n_phase - 1, 2 : 2 + width] = top
    keys = keys.reshape(n_guard * n_phase, columns)

    atom_of_piece = np.empty(n_base + keys.shape[0], dtype=np.int64)
    atom_of_piece[:n_base] = np.arange(n_base, dtype=np.int64)
    if keys.shape[0]:
        _unique, first, inverse = np.unique(
            keys, axis=0, return_index=True, return_inverse=True
        )
        inverse = inverse.reshape(-1)
        unique_keys = keys[first]
        # A K-only key with one cell (column 3 is the second cell, or J(k) = -1
        # when the sets have one column) is the key of a base piece.
        joins_base = (unique_keys[:, 0] == 0) & (unique_keys[:, 3] == -1)
        atom_of_class = np.empty(first.size, dtype=np.int64)
        atom_of_class[joins_base] = unique_keys[joins_base, 2]
        new = np.flatnonzero(~joins_base)
        rank = np.empty(new.size, dtype=np.int64)
        rank[np.argsort(first[new], kind="stable")] = np.arange(new.size)
        atom_of_class[new] = n_base + rank
        atom_of_piece[n_base:] = atom_of_class[inverse]

    # Generators: K_j(nu) for the level-j ancestors nu of the cells of R, and
    # Q_j(nu, c) for the level-j cells nu meeting the guard and the
    # 2^{j+2} - 2 middle phases c of level j.
    bottom_all = np.unique(np.concatenate([np.asarray(v, np.int64) for v in bottom_cells]))
    n_generators = 0
    for j in range(level + 1):
        side = 2 ** (j + level_offset)
        coarse = addresses >> (level - j)
        n_generators += int(np.unique(coarse[:, 0] * side + coarse[:, 1]).size)
        coarse = addresses[bottom_all] >> (level - j)
        n_generators += int(np.unique(coarse[:, 0] * side + coarse[:, 1]).size) * (
            2 ** (j + 2) - 2
        )
    return atom_of_piece, n_generators


def reference_signatures(
    grid: SuspensionGrid,
) -> tuple[tuple[tuple[int, ...], ...], tuple[GeneratorKey, ...], IntArray]:
    """Generator signatures of the pieces, enumerated generator by generator.

    Returns ``(signatures, generators, atom_of_piece)``: the sorted generator
    ids of every piece, the generator keys in the order of their ids, and the
    classes of equal signatures numbered by first piece.  This is the direct
    transcription of ``def:suspension-grid``;
    :func:`build_suspension_grid` computes the same atoms from short keys
    (:func:`_signature_classes`).  Its cost is linear in the number of
    generator memberships, so it is meant for tests and small grids.
    """

    level = grid.level
    addresses = grid.base_addresses
    generator_ids: dict[GeneratorKey, int] = {}

    def generator(key: GeneratorKey) -> int:
        value = generator_ids.get(key)
        if value is None:
            value = len(generator_ids)
            generator_ids[key] = value
        return value

    signatures: list[tuple[int, ...]] = []
    for address in addresses:
        signature = [
            generator(
                GeneratorKey(
                    "K",
                    j,
                    (int(address[0]) >> (level - j), int(address[1]) >> (level - j)),
                )
            )
            for j in range(level + 1)
        ]
        signatures.append(tuple(sorted(signature)))

    n_phase = grid.n_phase
    for guard_index in range(grid.n_guard):
        bottom_addresses = addresses[grid.guard_bottom_cells[guard_index]]
        top_addresses = addresses[grid.guard_top_cells[guard_index]]
        bottom_by_level = [
            sorted({(int(a) >> (level - j), int(b) >> (level - j)) for a, b in bottom_addresses})
            for j in range(level + 1)
        ]
        top_by_level = [
            sorted({(int(a) >> (level - j), int(b) >> (level - j)) for a, b in top_addresses})
            for j in range(level + 1)
        ]
        bottom_ids = [
            [generator(GeneratorKey("K", j, cell)) for cell in bottom_by_level[j]]
            for j in range(level + 1)
        ]
        top_ids = [
            [generator(GeneratorKey("K", j, cell)) for cell in top_by_level[j]]
            for j in range(level + 1)
        ]
        for phase in range(n_phase):
            signature: list[int] = []
            for j in range(level + 1):
                coarse_phase = phase >> (level - j)
                last = 2 ** (j + 2) - 1
                if coarse_phase == 0:
                    signature.extend(bottom_ids[j])
                elif coarse_phase == last:
                    signature.extend(top_ids[j])
                else:
                    signature.extend(
                        generator(GeneratorKey("Q", j, cell, coarse_phase))
                        for cell in bottom_by_level[j]
                    )
            signatures.append(tuple(sorted(set(signature))))

    atom_ids: dict[tuple[int, ...], int] = {}
    atom_of_piece = np.empty(len(signatures), dtype=np.int64)
    for piece, signature in enumerate(signatures):
        if not signature:
            raise AssertionError(f"piece {piece} lies in no generator")
        atom = atom_ids.get(signature)
        if atom is None:
            atom = len(atom_ids)
            atom_ids[signature] = atom
        atom_of_piece[piece] = atom
    keys: list[GeneratorKey | None] = [None] * len(generator_ids)
    for key, value in generator_ids.items():
        keys[value] = key
    return tuple(signatures), tuple(keys), atom_of_piece  # type: ignore[arg-type]


def _piece_adjacency(grid: SuspensionGrid) -> sparse.csr_matrix:
    """Pairs of pieces whose closures meet in ``Sigma X`` (symmetric)."""

    rows: list[IntArray] = []
    cols: list[IntArray] = []
    m = grid.cells_per_axis
    addresses = grid.base_addresses

    # Base/base: closed rectangles of the uniform grid meet iff the addresses
    # differ by at most one in each axis.
    for dx in (-1, 0, 1):
        for dy in (-1, 0, 1):
            nx = addresses[:, 0] + dx
            ny = addresses[:, 1] + dy
            ok = (nx >= 0) & (nx < m) & (ny >= 0) & (ny < m)
            neighbor = np.full(addresses.shape[0], -1, dtype=np.int64)
            neighbor[ok] = grid.base_cell_index[nx[ok], ny[ok]]
            keep = neighbor >= 0
            rows.append(np.flatnonzero(keep))
            cols.append(neighbor[keep])

    # Handle/handle in the chart G x [0,1]: consecutive guard intervals share
    # an endpoint, consecutive phase intervals share a phase.
    n_guard, n_phase = grid.n_guard, grid.n_phase
    gi, ki = np.meshgrid(np.arange(n_guard), np.arange(n_phase), indexing="ij")
    gi = gi.ravel()
    ki = ki.ravel()
    source = grid.handle_piece(gi, ki)
    for dg in (-1, 0, 1):
        for dk in (-1, 0, 1):
            ng = gi + dg
            nk = ki + dk
            ok = (ng >= 0) & (ng < n_guard) & (nk >= 0) & (nk < n_phase)
            rows.append(source[ok])
            cols.append(grid.handle_piece(ng[ok], nk[ok]))

    # Base/handle across the identifications: pi(J x {0}) = iota(gamma(J)) and
    # pi(J x {1}) = iota(r(gamma(J))).  The finest cells meeting gamma(J) are
    # those containing gamma at the endpoints or the midpoint of J, because J
    # crosses no grid line in its interior.
    def cells_meeting(curve: Callable[[FloatArray], FloatArray]) -> list[IntArray]:
        a = curve(grid.u_edges[:-1])
        b = curve(grid.u_edges[1:])
        c = curve(0.5 * (grid.u_edges[:-1] + grid.u_edges[1:]))
        located = [grid.locate_base_cells(points) for points in (a, b, c)]
        result: list[IntArray] = []
        for index in range(n_guard):
            result.append(
                np.unique(
                    np.concatenate(
                        [entry.piece[entry.point_index == index] for entry in located]
                    )
                )
            )
        return result

    guard_meets = cells_meeting(grid.guard.gamma)
    reset_meets = cells_meeting(grid.guard.reset)
    for index in range(n_guard):
        bottom = grid.handle_piece(index, 0)
        top = grid.handle_piece(index, n_phase - 1)
        rows.append(np.full(guard_meets[index].size, bottom))
        cols.append(guard_meets[index])
        rows.append(guard_meets[index])
        cols.append(np.full(guard_meets[index].size, bottom))
        rows.append(np.full(reset_meets[index].size, top))
        cols.append(reset_meets[index])
        rows.append(reset_meets[index])
        cols.append(np.full(reset_meets[index].size, top))

    # Handle/handle across the identifications: iota(gamma(J)) meets
    # iota(r(gamma(J'))).  Candidates share a finest cell; the exact test uses
    # the (polyline) curve pieces.
    guard_cell_sets = [set(values.tolist()) for values in guard_meets]
    reset_by_cell: dict[int, list[int]] = {}
    for index, values in enumerate(reset_meets):
        for cell in values.tolist():
            reset_by_cell.setdefault(cell, []).append(index)
    samples = 2 if (grid.guard_profile.straight and grid.reset_profile.straight) else 33
    tolerance = grid.location_tolerance * float(np.min(grid.cell_widths))
    pair_rows: list[int] = []
    pair_cols: list[int] = []
    for index, cells in enumerate(guard_cell_sets):
        candidates = sorted({other for cell in cells for other in reset_by_cell.get(cell, [])})
        if not candidates:
            continue
        guard_polyline = grid.guard.gamma(
            np.linspace(grid.u_edges[index], grid.u_edges[index + 1], samples)
        )
        for other in candidates:
            reset_polyline = grid.guard.reset(
                np.linspace(grid.u_edges[other], grid.u_edges[other + 1], samples)
            )
            if _segments_intersect(guard_polyline, reset_polyline, tolerance):
                bottom = int(grid.handle_piece(index, 0))
                top = int(grid.handle_piece(other, n_phase - 1))
                pair_rows.extend((bottom, top))
                pair_cols.extend((top, bottom))
    rows.append(np.asarray(pair_rows, dtype=np.int64))
    cols.append(np.asarray(pair_cols, dtype=np.int64))

    row = np.concatenate(rows)
    col = np.concatenate(cols)
    adjacency = sparse.csr_matrix(
        (np.ones(row.size), (row, col)), shape=(grid.n_pieces, grid.n_pieces)
    )
    adjacency.data[:] = 1.0
    return adjacency


