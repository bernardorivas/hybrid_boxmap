@dataclass(frozen=True)
class DyadicBaseWindow:
    """Dyadic base grids ``X_j`` on a window ``R`` inside an ambient rectangle.

    Level ``j`` subdivides ``ambient_bounds`` into ``2**(j + level_offset)``
    cells per axis.  ``region`` receives the centers of the finest cells as an
    ``(N, 2)`` array and returns the Boolean mask of cells contained in ``R``;
    ``None`` means ``R`` is the ambient rectangle.  ``R`` must be a union of
    finest cells, and the level-``j`` cells are the nonempty traces of the
    ambient level-``j`` cells on ``R``.
    """

    ambient_bounds: tuple[tuple[float, float], tuple[float, float]]
    level_offset: int = 0
    region: Callable[[FloatArray], npt.NDArray[np.bool_]] | None = None
    name: str = ""

    def __post_init__(self) -> None:
        bounds = tuple(
            (float(interval[0]), float(interval[1])) for interval in self.ambient_bounds
        )
        if len(bounds) != 2:
            raise UnsupportedSuspensionGridError(
                "the suspension grid is implemented for a two-dimensional base"
            )
        for lower, upper in bounds:
            if not (np.isfinite(lower) and np.isfinite(upper) and lower < upper):
                raise ValueError("ambient bounds must be finite nondegenerate intervals")
        object.__setattr__(self, "ambient_bounds", bounds)
        if isinstance(self.level_offset, bool) or int(self.level_offset) < 0:
            raise ValueError("level_offset must be a nonnegative integer")
        object.__setattr__(self, "level_offset", int(self.level_offset))

    def cells_per_axis(self, level: int) -> int:
        return 2 ** (int(level) + self.level_offset)

    def contains(
        self,
        points: npt.ArrayLike,
        level: int,
        *,
        tolerance: float = 1.0e-9,
    ) -> npt.NDArray[np.bool_]:
        """Closed membership in ``R`` (a union of level-``level`` cells)."""

        values = np.atleast_2d(np.asarray(points, dtype=np.float64))
        m = self.cells_per_axis(level)
        lower = np.array([self.ambient_bounds[0][0], self.ambient_bounds[1][0]])
        upper = np.array([self.ambient_bounds[0][1], self.ambient_bounds[1][1]])
        widths = (upper - lower) / m
        fractional = (values - lower) / widths
        finite = np.all(np.isfinite(fractional), axis=1)
        inside_box = finite & np.all(
            (fractional >= -tolerance) & (fractional <= m + tolerance), axis=1
        )
        if self.region is None:
            return inside_box
        result = np.zeros(values.shape[0], dtype=bool)
        for shift_x in (0.0, -tolerance, tolerance):
            for shift_y in (0.0, -tolerance, tolerance):
                cells = np.floor(fractional + np.array([shift_x, shift_y]))
                cells = np.clip(cells, 0, m - 1)
                centers = lower + (cells + 0.5) * widths
                candidate = inside_box & ~result
                if np.any(candidate):
                    inside = np.asarray(self.region(centers[candidate]), dtype=bool)
                    result[np.flatnonzero(candidate)[inside]] = True
        return result


@dataclass(frozen=True)
class GuardResetSpec:
    """Parametrized guard ``G cap R`` and reset ``r`` on it.

    ``guard_point(u)`` maps an array of guard coordinates in ``u_bounds`` to
    the ``(N, 2)`` base points ``gamma(u)``.  ``guard_coordinate(x)`` is the
    inverse chart on the whole guard ``G`` (it is also applied to guard points
    outside ``R`` to decide whether a handle endpoint lies in the window).
    ``reset_point(u)`` returns ``r(gamma(u))``.
    """

    u_bounds: tuple[float, float]
    guard_point: Callable[[FloatArray], FloatArray]
    guard_coordinate: Callable[[FloatArray], FloatArray]
    reset_point: Callable[[FloatArray], FloatArray]
    name: str = ""

    def __post_init__(self) -> None:
        lower, upper = (float(value) for value in self.u_bounds)
        if not (np.isfinite(lower) and np.isfinite(upper) and lower < upper):
            raise ValueError("u_bounds must be a finite nondegenerate interval")
        object.__setattr__(self, "u_bounds", (lower, upper))

    def gamma(self, u: npt.ArrayLike) -> FloatArray:
        values = np.atleast_1d(np.asarray(u, dtype=np.float64))
        points = np.asarray(self.guard_point(values), dtype=np.float64)
        return points.reshape(values.shape[0], 2)

    def reset(self, u: npt.ArrayLike) -> FloatArray:
        values = np.atleast_1d(np.asarray(u, dtype=np.float64))
        points = np.asarray(self.reset_point(values), dtype=np.float64)
        return points.reshape(values.shape[0], 2)

    def coordinate(self, x: npt.ArrayLike) -> FloatArray:
        points = np.atleast_2d(np.asarray(x, dtype=np.float64))
        return np.asarray(self.guard_coordinate(points), dtype=np.float64).reshape(-1)


