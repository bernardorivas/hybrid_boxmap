@dataclass(frozen=True)
class SuspensionGridCheck:
    """Piece-level verification of the grid statements of the manuscript."""

    pieces_disjoint_interiors: bool
    pieces_cover_window: bool
    d_injective: bool
    d_base_preimage_exact: bool
    d_contains_interior: bool
    atoms_nonempty: bool

    @property
    def passed(self) -> bool:
        return all(
            (
                self.pieces_disjoint_interiors,
                self.pieces_cover_window,
                self.d_injective,
                self.d_base_preimage_exact,
                self.d_contains_interior,
                self.atoms_nonempty,
            )
        )


def check_suspension_grid(grid: SuspensionGrid) -> SuspensionGridCheck:
    """Verify ``prop:suspension-grid`` and the grid axioms at the piece level.

    * Pieces have pairwise disjoint interiors and cover ``D``: base cells are
      distinct finest cells, handle pieces are products of a partition of
      ``G cap R`` with the phase grid (checked through areas).
    * ``d_n`` is injective and ``iota^{-1}(|d_n(mu)|) = |mu|``: the only base
      piece of ``d_n(mu)`` is ``mu``, and every handle piece of ``d_n(mu)``
      has its seam trace (``gamma(J)`` at phase 0, ``r(gamma(J))`` at phase 1)
      inside ``|mu|``.
    * ``iota(Int|mu|) subset Int|d_n(mu)|``: every seam piece whose trace
      meets ``Int|mu|`` (trace in the single cell ``mu``) belongs to
      ``d_n(mu)``.
    """

    # Base pieces are distinct finest cells of R; handle pieces are products of
    # a partition of G cap R with the phase grid.  Each piece has exactly one
    # atom, so the atoms have disjoint interiors and cover the window.
    disjoint = bool(
        np.unique(grid.base_addresses, axis=0).shape[0] == grid.n_base
        and np.all(np.diff(grid.u_edges) > 0.0)
    )
    cover = bool(
        grid.u_edges[0] == grid.guard.u_bounds[0]
        and grid.u_edges[-1] == grid.guard.u_bounds[1]
        and int(np.count_nonzero(grid.base_cell_index >= 0)) == grid.n_base
        and grid.atom_of_piece.shape[0] == grid.n_pieces
        and np.all((grid.atom_of_piece >= 0) & (grid.atom_of_piece < grid.n_atoms))
    )

    d_injective = bool(np.unique(grid.d_map).size == grid.n_base)
    owner = np.full(grid.n_atoms, -1, dtype=np.int64)
    owner[grid.d_map] = np.arange(grid.n_base)
    base_count = np.bincount(grid.atom_of_piece[: grid.n_base], minlength=grid.n_atoms)
    preimage_exact = bool(np.all(base_count[grid.d_map] == 1))
    contains_interior = True
    for index in range(grid.n_guard):
        for phase, cells in (
            (0, grid.guard_bottom_cells[index]),
            (grid.n_phase - 1, grid.guard_top_cells[index]),
        ):
            atom = int(grid.atom_of_piece[grid.handle_piece(index, phase)])
            mu = int(owner[atom])
            if mu >= 0 and mu not in set(cells.tolist()):
                # A seam piece of d_n(mu) must have its trace inside |mu|.
                preimage_exact = False
            if cells.size == 1 and grid.d_map[cells[0]] != atom:
                # A trace in a single cell mu (relative interior) forces the
                # seam piece into the atom containing iota(Int|mu|).
                contains_interior = False
    # Middle phase pieces never meet iota(X) and must avoid d_n(X_n).
    guard_index, phase = grid.handle_indices(np.arange(grid.n_base, grid.n_pieces))
    middle = (phase > 0) & (phase < grid.n_phase - 1)
    if np.any(owner[grid.atom_of_piece[grid.n_base :][middle]] >= 0):
        preimage_exact = False
    atoms_nonempty = bool(np.all(np.diff(grid.atom_offsets) > 0))
    return SuspensionGridCheck(
        pieces_disjoint_interiors=disjoint,
        pieces_cover_window=cover,
        d_injective=d_injective,
        d_base_preimage_exact=preimage_exact,
        d_contains_interior=contains_interior,
        atoms_nonempty=atoms_nonempty,
    )


