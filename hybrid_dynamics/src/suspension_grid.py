@dataclass(frozen=True)
class _CurveProfile:
    """Per-coordinate monotonicity classification of a parametrized curve."""

    kinds: tuple[str, str]  # "constant", "increasing", "decreasing"
    straight: bool


def _curve_profile(
    curve: Callable[[FloatArray], FloatArray],
    u_bounds: tuple[float, float],
    *,
    scale: tuple[float, float],
    name: str,
    samples: int = 4097,
) -> _CurveProfile:
    u = np.linspace(u_bounds[0], u_bounds[1], samples)
    points = curve(u)
    if points.shape != (samples, 2) or not np.all(np.isfinite(points)):
        raise ValueError(f"{name} must return finite (N, 2) points")
    kinds: list[str] = []
    for axis in range(2):
        values = points[:, axis]
        tolerance = 1.0e-12 * max(scale[axis], float(np.max(np.abs(values))), 1.0)
        span = float(np.max(values) - np.min(values))
        if span <= tolerance:
            kinds.append("constant")
            continue
        steps = np.diff(values)
        if np.all(steps > 0.0):
            kinds.append("increasing")
        elif np.all(steps < 0.0):
            kinds.append("decreasing")
        else:
            raise UnsupportedSuspensionGridError(
                f"coordinate {axis} of {name} is neither constant nor strictly "
                "monotone on the guard interval; the grid crossings of such a "
                "curve are not implemented"
            )
    chord = points[-1] - points[0]
    length = float(np.hypot(*chord))
    if length == 0.0:
        raise UnsupportedSuspensionGridError(f"{name} is constant on the guard interval")
    normal = np.array((-chord[1], chord[0])) / length
    deviation = float(np.max(np.abs((points - points[0]) @ normal)))
    straight = deviation <= 1.0e-10 * max(length, 1.0)
    return _CurveProfile(kinds=(kinds[0], kinds[1]), straight=straight)


def _bisect_level(
    curve: Callable[[FloatArray], FloatArray],
    axis: int,
    increasing: bool,
    targets: FloatArray,
    u_bounds: tuple[float, float],
    iterations: int = 80,
) -> FloatArray:
    """Solve ``curve(u)[axis] = target`` for a strictly monotone coordinate."""

    lower = np.full(targets.shape, u_bounds[0], dtype=np.float64)
    upper = np.full(targets.shape, u_bounds[1], dtype=np.float64)
    for _ in range(iterations):
        middle = 0.5 * (lower + upper)
        values = curve(middle)[:, axis]
        below = values < targets if increasing else values > targets
        lower = np.where(below, middle, lower)
        upper = np.where(below, upper, middle)
        if np.all(upper - lower <= 4.0 * np.finfo(float).eps * np.maximum(1.0, np.abs(upper))):
            break
    return 0.5 * (lower + upper)


def _curve_grid_crossings(
    curve: Callable[[FloatArray], FloatArray],
    profile: _CurveProfile,
    u_bounds: tuple[float, float],
    grid_lines: Sequence[FloatArray],
) -> FloatArray:
    """Parameters at which a monotone curve crosses finest-grid lines."""

    endpoints = curve(np.asarray(u_bounds, dtype=np.float64))
    crossings: list[FloatArray] = []
    for axis in range(2):
        kind = profile.kinds[axis]
        if kind == "constant":
            continue
        low = min(endpoints[0, axis], endpoints[1, axis])
        high = max(endpoints[0, axis], endpoints[1, axis])
        lines = np.asarray(grid_lines[axis], dtype=np.float64)
        inside = lines[(lines > low) & (lines < high)]
        if inside.size:
            crossings.append(
                _bisect_level(curve, axis, kind == "increasing", inside, u_bounds)
            )
    if not crossings:
        return np.zeros(0, dtype=np.float64)
    return np.concatenate(crossings)


def _invert_curve(
    curve: Callable[[FloatArray], FloatArray],
    profile: _CurveProfile,
    u_bounds: tuple[float, float],
    points: FloatArray,
) -> FloatArray:
    """Invert a monotone curve on the points; ``nan`` where ill-defined."""

    ends = curve(np.asarray(u_bounds, dtype=np.float64))
    spans = np.abs(ends[1] - ends[0])
    candidates = [axis for axis in range(2) if profile.kinds[axis] != "constant"]
    axis = max(candidates, key=lambda index: spans[index])
    increasing = profile.kinds[axis] == "increasing"
    targets = np.clip(
        points[:, axis],
        min(ends[0, axis], ends[1, axis]),
        max(ends[0, axis], ends[1, axis]),
    )
    return _bisect_level(curve, axis, increasing, targets, u_bounds)


def _segments_intersect(
    first: FloatArray,
    second: FloatArray,
    tolerance: float,
) -> bool:
    """Closed polyline intersection test with an absolute tolerance."""

    for a0, a1 in zip(first[:-1], first[1:]):
        for b0, b1 in zip(second[:-1], second[1:]):
            if _segment_pair_intersect(a0, a1, b0, b1, tolerance):
                return True
    return False


def _segment_pair_intersect(
    p0: FloatArray, p1: FloatArray, q0: FloatArray, q1: FloatArray, tol: float
) -> bool:
    def point_segment_distance(point: FloatArray, a: FloatArray, b: FloatArray) -> float:
        direction = b - a
        denominator = float(direction @ direction)
        if denominator == 0.0:
            return float(np.hypot(*(point - a)))
        t = float(np.clip((point - a) @ direction / denominator, 0.0, 1.0))
        return float(np.hypot(*(point - (a + t * direction))))

    def cross(a: FloatArray, b: FloatArray) -> float:
        return float(a[0] * b[1] - a[1] * b[0])

    r = p1 - p0
    s = q1 - q0
    denominator = cross(r, s)
    if denominator != 0.0:
        t = cross(q0 - p0, s) / denominator
        v = cross(q0 - p0, r) / denominator
        if -1.0e-12 <= t <= 1.0 + 1.0e-12 and -1.0e-12 <= v <= 1.0 + 1.0e-12:
            return True
    return min(
        point_segment_distance(p0, q0, q1),
        point_segment_distance(p1, q0, q1),
        point_segment_distance(q0, p0, p1),
        point_segment_distance(q1, p0, p1),
    ) <= tol


