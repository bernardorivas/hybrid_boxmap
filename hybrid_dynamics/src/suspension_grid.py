"""Suspension grids of the manuscript (Definition ``def:suspension-grid``).

This module constructs the grid ``Xi_n`` on a computational window of the
hybrid suspension ``Sigma X`` exactly as the manuscript defines it, for a
two-dimensional base with a one-dimensional guard:

* the phase grids ``I_{n,k} = [k a_n, (k+1) a_n]`` with ``a_n = 2^{-n-2}``;
* a contracting cofiltration ``(X_j)`` of base grids obtained from one ambient
  rectangle by repeated halving (level ``j`` has ``2^{j + level_offset}``
  cells per axis), traced on a window ``R`` that is a union of finest cells;
* the generators ``K_j(mu)`` (regularized ``E_j(mu)``) and ``Q_j(mu, k)`` for
  every level ``j <= n``, so that ``Xi_n = Xi_{n-1} ^ Xi_n(X_n)`` is the
  common refinement used by the manuscript; and
* the atoms of the Boolean algebra generated by these sets.

Every generator is a finite union of *elementary pieces*:

* base pieces, the finest base cells ``|mu|`` of level ``n``; and
* handle pieces ``pi(J x I_{n,k})``, where ``J`` runs over the common
  refinement of the guard intervals ``|mu| cap G`` and ``r^{-1}(|mu|)``
  (all levels ``j <= n``; the level-``n`` breakpoints contain those of the
  coarser levels) and ``I_{n,k}`` over the phase grid of level ``n``.

A piece lies in ``K_j(nu)``, ``Q_j(nu, k)`` or neither; its *signature* is the
set of generators containing it.  Since every piece is a regular closed set
with nonempty interior and the pieces form a grid on the window, the atoms of
the generated Boolean algebra are exactly the nonempty unions of pieces with a
common signature.  Degenerate parts of ``E_j(mu)`` (for example a cell that
meets the guard only at a corner) have empty interior and are removed by the
regularization; at the piece level they simply contain no piece.

The window is ``D = Sigma(R) = iota(R) cup pi((G cap R) x [0,1])``.  The
module requires ``r(G cap R) subset R`` so that every top collar lies over a
base cell of ``R``; this holds for all examples of the manuscript.

The guard is described by a parametrization ``u -> gamma(u)`` of ``G cap R``
over an interval and the reset by ``u -> r(gamma(u))``.  Each coordinate of
both maps must be constant or strictly monotone on the interval; the grid
crossings are then computed exactly (by bisection) and a clear error is
raised for unsupported non-monotone data.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from typing import Any

import numpy as np
import numpy.typing as npt
from scipy import sparse


FloatArray = npt.NDArray[np.float64]
IntArray = npt.NDArray[np.int64]

BASE_PIECE = 0
HANDLE_PIECE = 1


class UnsupportedSuspensionGridError(NotImplementedError):
    """Raised for guard/reset data outside the implemented setting."""


