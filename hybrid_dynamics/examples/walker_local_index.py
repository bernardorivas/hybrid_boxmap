"""Exit-aware local index pairs for persisted CMGDB Atlas relations.

This module works at the level of a finite, already persisted Atlas relation.
It does not resample a hybrid trajectory and does not infer a continuous-system
Conley index.  Starting from a recorded Morse SCC ``S``, it constructs a
geometric collar ``N`` and the least represented exit set ``L`` generated by

* source flags saying that an image has an open/ambient exit, and
* represented relation edges from a source in ``N`` to a target outside ``N``.

It then closes ``L`` under represented images inside ``N``.  The resulting
certificate explicitly checks

``F(N \\ L) subset N`` and ``F(L) intersection N subset L``, rejects
``S intersection L``, and verifies that ``S`` is the only recurrent component
of the represented relation in ``N \\ L``.

Atlas rectangles may have arbitrary sizes.  No uniform-grid or single-depth
assumption is made.  Same-chart collar adjacency is closed-box contact;
cross-chart reset identifications must be supplied as explicit quotient
neighbor pairs.
"""

