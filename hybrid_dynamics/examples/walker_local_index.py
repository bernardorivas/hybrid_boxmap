@dataclass(frozen=True)
class _PersistedRelation:
    model: str
    depth: int
    t_star: float
    cells: tuple[_PersistedRelationCell, ...]
    relation_scope: str
    whole_cell_outer_enclosure_certified: bool

    def morse_set(self, node: int) -> frozenset[int]:
        result = frozenset(
            cell.index for cell in self.cells if cell.morse_node == int(node)
        )
        if not result:
            raise ValueError(f"Morse node {node} has no cells in this relation")
        return result


