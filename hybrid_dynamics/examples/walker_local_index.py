EXIT_AWARE_LOCAL_INDEX_INPUT_SCHEMA = "exit-aware-local-index-input-v1"
EXIT_AWARE_LOCAL_INDEX_CERTIFICATE_SCHEMA = (
    "exit-aware-local-index-pair-certificate-v1"
)
GARCIA_WALKER_OPEN_EXIT_RELATION_SCHEMA = (
    "garcia-walker-open-exit-atlas-relation-v1"
)


def _frozen_bool_mapping(values: Mapping[int, bool]) -> Mapping[int, bool]:
    normalized = {}
    for source, flag in values.items():
        if not isinstance(flag, bool):
            raise ValueError(f"open-exit flag for cell {source} must be boolean")
        normalized[int(source)] = flag
    if len(normalized) != len(values):
        raise ValueError("source-exit flags contain duplicate integer ids")
    return MappingProxyType(normalized)


def _normalized_pairs(
    pairs: Iterable[Sequence[int]],
    *,
    name: str,
) -> tuple[tuple[int, int], ...]:
    normalized: set[tuple[int, int]] = set()
    for raw_pair in pairs:
        pair = tuple(int(value) for value in raw_pair)
        if len(pair) != 2:
            raise ValueError(f"every {name} entry must contain two cell ids")
        if pair[0] == pair[1]:
            raise ValueError(f"{name} must not contain self-pairs")
        normalized.add(tuple(sorted(pair)))
    return tuple(sorted(normalized))


@dataclass(frozen=True)
class ExitAwareLocalIndexInput:
    """Serializable inputs not already contained in an Atlas relation cache."""

    morse_node: int
    collar_layers: int
    open_exit_flags: Mapping[int, bool]
    allowed_cells: frozenset[int] | None = None
    quotient_neighbor_pairs: tuple[tuple[int, int], ...] = ()
    metadata: Mapping[str, object] = MappingProxyType({})

    def __post_init__(self) -> None:
        if int(self.collar_layers) < 0:
            raise ValueError("collar_layers must be nonnegative")
        allowed = (
            None
            if self.allowed_cells is None
            else frozenset(int(cell) for cell in self.allowed_cells)
        )
        if allowed is not None and not allowed:
            raise ValueError("allowed_cells must be nonempty when supplied")
        object.__setattr__(self, "morse_node", int(self.morse_node))
        object.__setattr__(self, "collar_layers", int(self.collar_layers))
        object.__setattr__(
            self,
            "open_exit_flags",
            _frozen_bool_mapping(self.open_exit_flags),
        )
        object.__setattr__(self, "allowed_cells", allowed)
        object.__setattr__(
            self,
            "quotient_neighbor_pairs",
            _normalized_pairs(
                self.quotient_neighbor_pairs,
                name="quotient_neighbor_pairs",
            ),
        )
        object.__setattr__(self, "metadata", MappingProxyType(dict(self.metadata)))

    def to_json_dict(self) -> dict[str, object]:
        return {
            "schema": EXIT_AWARE_LOCAL_INDEX_INPUT_SCHEMA,
            "morse_node": self.morse_node,
            "collar_layers": self.collar_layers,
            "allowed_cells": (
                None
                if self.allowed_cells is None
                else sorted(self.allowed_cells)
            ),
            "source_exit_flags": [
                {"source": source, "open_exit": flag}
                for source, flag in sorted(self.open_exit_flags.items())
            ],
            "quotient_neighbor_pairs": [
                list(pair) for pair in self.quotient_neighbor_pairs
            ],
            "metadata": dict(self.metadata),
        }

    def write_json(self, path: str | Path) -> Path:
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            json.dumps(self.to_json_dict(), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        return target

    @classmethod
    def read_json(cls, path: str | Path) -> "ExitAwareLocalIndexInput":
        source = Path(path)
        payload = json.loads(source.read_text(encoding="utf-8"))
        if payload.get("schema") != EXIT_AWARE_LOCAL_INDEX_INPUT_SCHEMA:
            raise ValueError(f"{source} has an unsupported local-index input schema")
        raw_flags = payload.get("source_exit_flags", [])
        if not isinstance(raw_flags, list):
            raise ValueError("source_exit_flags must be a list")
        flags: dict[int, bool] = {}
        for record in raw_flags:
            if not isinstance(record, dict):
                raise ValueError("each source-exit flag must be an object")
            source_id = int(record["source"])
            if source_id in flags:
                raise ValueError(f"duplicate source-exit flag for cell {source_id}")
            flag = record.get("open_exit")
            if not isinstance(flag, bool):
                raise ValueError(f"open_exit for cell {source_id} must be boolean")
            flags[source_id] = flag
        raw_allowed = payload.get("allowed_cells")
        allowed = (
            None
            if raw_allowed is None
            else frozenset(int(cell) for cell in raw_allowed)
        )
        metadata = payload.get("metadata", {})
        if not isinstance(metadata, dict):
            raise ValueError("input metadata must be an object")
        return cls(
            morse_node=int(payload["morse_node"]),
            collar_layers=int(payload["collar_layers"]),
            open_exit_flags=flags,
            allowed_cells=allowed,
            quotient_neighbor_pairs=tuple(
                tuple(int(value) for value in pair)
                for pair in payload.get("quotient_neighbor_pairs", [])
            ),
            metadata=metadata,
        )


@dataclass(frozen=True)
class _Rectangle:
    index: int
    chart_id: int
    lower: tuple[float, ...]
    upper: tuple[float, ...]

    @property
    def dimension(self) -> int:
        return len(self.lower)

    @property
    def center(self) -> tuple[float, ...]:
        return tuple(
            (lower + upper) / 2.0
            for lower, upper in zip(self.lower, self.upper)
        )

    @property
    def half_width(self) -> tuple[float, ...]:
        return tuple(
            (upper - lower) / 2.0
            for lower, upper in zip(self.lower, self.upper)
        )

    @property
    def width(self) -> tuple[float, ...]:
        return tuple(
            upper - lower for lower, upper in zip(self.lower, self.upper)
        )


